    fn same(expected: &serde_json::Value, got: &Value) -> bool {
        match expected {
            serde_json::Value::Null => matches!(got, Value::Null),
            serde_json::Value::Bool(flag) => matches!(got, Value::Bool(other) if other == flag),
            serde_json::Value::Number(number) => {
                let expected = number.as_f64().unwrap_or_default();
                match got {
                    Value::Int(value) => *value as f64 == expected,
                    Value::Float(value) => (*value - expected).abs() <= 1e-9 * expected.abs().max(1.0),
                    _ => false,
                }
            }
            serde_json::Value::String(text) => match got {
                Value::Text(other) => other == text,
                Value::Bytes(bytes) => hex(bytes).eq_ignore_ascii_case(text),
                _ => false,
            },
            serde_json::Value::Array(items) => match got {
                Value::List(values) => {
                    values.len() == items.len()
                        && items.iter().zip(values).all(|(item, value)| same(item, value))
                }
                _ => false,
            },
            serde_json::Value::Object(entries) => match got {
                Value::Map(values) => entries.iter().filter(|(key, _)| !ignored(key)).all(
                    |(key, expected)| {
                        values
                            .iter()
                            .find(|(name, _)| name == key)
                            .map(|(_, value)| same(expected, value))
                            .unwrap_or(false)
                    },
                ),
                _ => false,
            },
        }
    }

