    #[test]
    fn decoded_values_match_the_reference() {
        let spec = Spec::embedded().expect("the embedded specification must parse");
        let document: serde_json::Value = serde_json::from_str(VECTORS).expect("vectors are JSON");
        let vectors = document["vectors"].as_array().expect("vectors array");

        let mut per_format: Vec<(String, u32, u32)> = Vec::new();
        let mut failures: Vec<String> = Vec::new();
        for vector in vectors {
            let format = vector["format"].as_str().unwrap_or_default().to_string();
            let payload = from_hex(vector["payload"].as_str().unwrap_or_default());
            let expected = vector.get("decoded").cloned();
            let decoded = Decoder::new(&spec, &payload).decode(&format);

            let agrees = match &expected {
                // The reference decoded it: every field must match.
                Some(wanted) => match &decoded {
                    Ok(value) => same(wanted, value),
                    Err(_) => false,
                },
                // The reference rejected it: we must reject it too.
                None => decoded.is_err(),
            };
            let position = per_format
                .iter()
                .position(|(name, _, _)| *name == format)
                .unwrap_or_else(|| {
                    per_format.push((format.clone(), 0, 0));
                    per_format.len() - 1
                });
            per_format[position].1 += 1;
            if agrees {
                per_format[position].2 += 1;
            } else if failures.iter().filter(|entry| entry.starts_with(&format)).count() < 2 {
                failures.push(format!(
                    "{format} {}\n    expected {:?}\n    got {:?}",
                    vector["payload"].as_str().unwrap_or_default(),
                    expected.as_ref().map(|value| value.to_string()),
                    decoded.as_ref().map(|value| format!("{value:?}")).map_err(|error| error.0.clone())
                ));
            }
        }

        println!("\n  formato        vettori  concordi");
        for (format, total, ok) in &per_format {
            println!("  {format:<14} {total:>7} {ok:>10}   {}", if ok == total { "ok" } else { "" });
        }
        if !failures.is_empty() {
            println!("\n  primi disaccordi:\n    {}", failures.join("\n    "));
        }

        for format in ENFORCED {
            let (_, total, ok) = per_format
                .iter()
                .find(|(name, _, _)| name == format)
                .unwrap_or_else(|| panic!("no vectors for the enforced format {format}"));
            assert_eq!(ok, total, "{format}: {ok} of {total} vectors agree with the reference");
        }
    }

